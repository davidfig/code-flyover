// Which files go on the map, and what each is for.
//
// Code is any file in a language the analyzer reads for dependencies (shared/languages.ts). Docs are Markdown and
// plain text. Everything else that's text (config, styles, templates, scripts in languages we only colour) is on the
// map too, as the fallback: shown and diffed like code, linked by the repo paths it quotes. Binaries, build output
// and dependencies' folders stay off.

import { BINARY, languageOf } from '../shared/languages.ts'
import type { FileRole } from '../shared/types.ts'

export const SKIP_DIR = /(^|\/)(node_modules|dist|build|target|vendor|public|generated|\.claude|coverage|__pycache__|\.venv|venv|\.tox|Pods|Carthage|\.gradle|\.dart_tool|DerivedData|bower_components|jspm_packages)\//

/** Past this a fallback file stays off the map: a data dump or vendored bundle, not something to review. */
export const MAX_FALLBACK_BYTES = 512 * 1024

const MINIFIED = /\.min\.(js|css)$|\.d\.ts$|\.bundle\.js$/
const DOC_NAMES = /(^|\/)(LICEN[CS]E|COPYING|NOTICE|AUTHORS|CONTRIBUTORS|CHANGELOG|CHANGES|HISTORY|README)$/

/** A file in a language whose dependencies the analyzer finds. */
export const isCode = (f: string) => !SKIP_DIR.test(f) && !MINIFIED.test(f) && !!languageOf(f)?.deps

/** Markdown and plain text: on the map as docs, muted like tests. */
export const isDoc = (f: string) => !SKIP_DIR.test(f) && !languageOf(f) && (/\.(md|mdx|markdown|txt|rst|adoc|asciidoc|org)$/i.test(f) || DOC_NAMES.test(f))

/** Any other file that's probably text. Its contents still have to pass `isText` once read. */
export const isFallback = (f: string) => !SKIP_DIR.test(f) && !MINIFIED.test(f) && !BINARY.test(f) && !isCode(f) && !isDoc(f)

/** Read contents that are worth showing as a fallback file: not binary, not huge. */
export const isText = (s: string | undefined) => s !== undefined && s.length <= MAX_FALLBACK_BYTES && !s.slice(0, 8000).includes('\0')

/** The files the map can show, before their contents are checked: code, docs, and the fallback. */
export const onMap = (f: string) => isCode(f) || isDoc(f) || isFallback(f)

/** A programming language (not data or config): counts toward "source changed without tests". */
export const isProgram = (f: string) => !!languageOf(f)?.code

export const isTest = (f: string) =>
  /(^|\/)(test|tests|__tests__|e2e|spec|specs|Tests|UnitTests|IntegrationTests|androidTest|testFixtures)\//.test(f) ||
  /(^|\/)[\w.-]*[a-z.](Tests?|Specs?)\//.test(f) || // MyApp.Tests/, MyAppTests/
  /\.(test|spec)\.\w+$/.test(f) || // a.test.ts, a.spec.rb
  /(^|\/)test_[^/]+\.py$|_test\.(py|go|rb|dart|exs|rs|cc|cpp|c)$|_spec\.rb$/.test(f) ||
  /[a-z0-9](Test|Tests|Spec|IT)\.(cs|java|kt|kts|scala|swift|php|groovy|m|mm)$/.test(f) ||
  /(^|\/)conftest\.py$/.test(f)

const isLocale = (f: string) => /(^|\/)(i18n|locales?|l10n|translations?|lang)\//.test(f) || /\.(po|pot|xliff|xlf|resx|strings|stringsdict)$/.test(f)

const LOCKFILE =
  /(^|\/)(package-lock\.json|npm-shrinkwrap\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lock|Cargo\.lock|poetry\.lock|Pipfile\.lock|uv\.lock|pdm\.lock|composer\.lock|Gemfile\.lock|go\.sum|Podfile\.lock|Package\.resolved|pubspec\.lock|mix\.lock|flake\.lock|packages\.lock\.json|gradle\.lockfile|Cartfile\.resolved)$/

const isGenerated = (f: string) =>
  LOCKFILE.test(f) ||
  /(^|\/)(autogenerated|__generated__|gen|Generated)\//.test(f) ||
  /\.(gen|generated|g|g\.i|designer|pb|pb\.gw|freezed|mocks)\.\w+$/i.test(f) ||
  /_pb2(_grpc)?\.pyi?$|_generated\.go$|\.Designer\.cs$/.test(f)

export const roleOf = (f: string): FileRole =>
  isDoc(f) ? 'doc' : isTest(f) ? 'test' : isGenerated(f) ? 'generated' : isLocale(f) ? 'locale' : 'source'
